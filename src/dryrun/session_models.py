"""
session_models.py

Persistent session structures for DryRun.

These models store:
- Debate rounds
- Revision history
- Consensus evolution
- Final decision packet

Used by:
- SessionRunner
- SessionStore
- Streamlit dashboard
- Evaluator
"""

from pydantic import BaseModel, Field
from typing import List, Dict

from dryrun.schemas import (
    CTOMemo,
    CMOMemo,
    CFOMemo,
    LegalMemo,
    SalesMemo,
    DevilsBrief,
    DecisionPacket,
)


# ──────────────────────────────────────────────────────────────
# Single debate round
# ──────────────────────────────────────────────────────────────

class DebateRound(BaseModel):
    """
    Snapshot of one complete debate round.
    """

    round_num: int

    cto_memo: CTOMemo
    cmo_memo: CMOMemo
    cfo_memo: CFOMemo
    legal_memo: LegalMemo
    sales_memo: SalesMemo

    devils_brief: DevilsBrief

    revised_agents: List[str] = Field(
        default_factory=list,
        description="Agents forced to revise this round"
    )

    consensus_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )


# ──────────────────────────────────────────────────────────────
# Revision event
# ──────────────────────────────────────────────────────────────

class RevisionEvent(BaseModel):
    """
    Tracks one revision requested by the debate engine.
    """

    round_num: int

    agent_name: str

    reason: str

    previous_confidence: float

    new_confidence: float


# ──────────────────────────────────────────────────────────────
# Session timeline event
# ──────────────────────────────────────────────────────────────

class SessionEvent(BaseModel):
    """
    Generic event for timeline visualizations.
    """

    event_type: str

    message: str

    round_num: int | None = None


# ──────────────────────────────────────────────────────────────
# Full boardroom session
# ──────────────────────────────────────────────────────────────

class DebateSession(BaseModel):
    """
    Entire DryRun boardroom session.
    """

    problem: str

    company_context: str

    rounds: List[DebateRound] = Field(default_factory=list)

    revision_history: List[RevisionEvent] = Field(
        default_factory=list
    )

    timeline: List[SessionEvent] = Field(
        default_factory=list
    )

    final_packet: DecisionPacket | None = None

    total_rounds: int = 0

    final_consensus_score: float = Field(
        default=0.0,
        ge=0.0,
        le=1.0
    )


# ──────────────────────────────────────────────────────────────
# Dashboard-ready session summary
# ──────────────────────────────────────────────────────────────

class SessionSummary(BaseModel):
    """
    Lightweight view used by Streamlit.
    """

    total_rounds: int

    final_consensus_score: float

    ceo_confidence: float

    dissenting_agents: List[str]

    revised_agents: List[str]

    final_decision: str


# ──────────────────────────────────────────────────────────────
# Analytics payload
# ──────────────────────────────────────────────────────────────

class SessionAnalytics(BaseModel):
    """
    Metrics generated by evaluator.py
    """

    consensus_trend: List[float]

    confidence_trend: Dict[str, List[float]]

    revision_counts: Dict[str, int]

    dissent_frequency: Dict[str, int]